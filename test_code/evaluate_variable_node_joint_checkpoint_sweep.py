def main() -> None:
    args = parse_args()
    results_dir = Path(args.results_dir).expanduser().resolve()
    plots_dir = results_dir / "plots"
    results_dir.mkdir(parents=True, exist_ok=True)

    with open(results_dir / f"{args.summary_prefix}_args.json", "w", encoding="utf-8") as handle:
        json.dump(vars(args), handle, indent=2, ensure_ascii=False)

    aggregate, by_sem, detailed = evaluate(args)
    aggregate_path = results_dir / f"{args.summary_prefix}_aggregate.csv"
    by_sem_path = results_dir / f"{args.summary_prefix}_by_sem.csv"
    detailed_path = results_dir / f"{args.summary_prefix}_detailed.csv"
    aggregate.to_csv(aggregate_path, index=False)
    by_sem.to_csv(by_sem_path, index=False)
    detailed.to_csv(detailed_path, index=False)
    print(f"Wrote aggregate summary: {aggregate_path}")
    print(f"Wrote SEM summary:       {by_sem_path}")
    print(f"Wrote detailed summary:  {detailed_path}")
    if aggregate.empty or "n_ok" not in aggregate.columns or int(aggregate["n_ok"].sum()) == 0:
        raise RuntimeError(
            "All evaluations failed: aggregate n_ok is 0. "
            "Re-run with --print_errors to inspect the first failures."
        )

    plot_node_counts = parse_int_list(args.plot_node_counts) if args.plot_node_counts else None
    plot_sample_sizes = parse_int_list(args.plot_sample_sizes) if args.plot_sample_sizes else None
    plot_paths = save_metric_plots(
        aggregate,
        plots_dir,
        args.summary_prefix,
        plot_groups=parse_csv_list(args.plot_groups),
        plot_node_counts=plot_node_counts,
        plot_sample_sizes=plot_sample_sizes,
    )
    if plot_paths:
        print(f"Wrote {len(plot_paths)} plots under: {plots_dir}")


if __name__ == "__main__":
    main()
