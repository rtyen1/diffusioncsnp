"""Evaluate variable-node joint DAG predictions against PC/GES CPDAGs.

This is the variable-node counterpart of
``test_code/evaluate_joint_dag_cpdag_vs_traditional.py``.  It reads benchmark
shards generated by ``generate_diverse_train_data.py``:

    <benchmark_root>/<split>/d{D}_shard_*.hdf5

The learned joint topo+skeleton model is converted to a DAG by thresholding the
predicted skeleton and orienting every selected edge according to the sampled
topological order.  Both learned and traditional predictions are converted to
CPDAGs, then compared to the true CPDAG using only:

    cpdag_exact_match, cpdag_shd_pairwise
"""

